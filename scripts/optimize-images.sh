#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Generates responsive AVIF copies of every JPEG in public/images/ (macOS only —
# uses the built-in `sips` tool, no npm packages) and writes the manifest the
# <Img> component reads. Originals are never modified and remain the fallback.
#
#   bash scripts/optimize-images.sh
#
# Run it again whenever you add or replace photos in public/images/.
# Images not in the manifest still work — they're just served as plain JPEGs.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=public/images
OUT=public/images/opt
MANIFEST=src/config/images.generated.js
WIDTHS=(640 1280 1920)
QUALITY=55
SKIP=(og-image.jpg) # social-share image must stay a JPEG

command -v sips >/dev/null || { echo "sips not found — this script needs macOS." >&2; exit 1; }
mkdir -p "$OUT"

{
  echo "// AUTO-GENERATED by scripts/optimize-images.sh — do not edit by hand."
  echo "// Maps each original image to the AVIF widths available in /images/opt/."
  echo "export const imageVariants = {"
} > "$MANIFEST"

for f in "$SRC"/*.jpg "$SRC"/*.jpeg; do
  [ -e "$f" ] || continue
  name=$(basename "$f")
  [[ " ${SKIP[*]} " == *" $name "* ]] && continue
  base="${name%.*}"
  w=$(sips -g pixelWidth "$f" | awk '/pixelWidth/{print $2}')
  made=()
  for t in "${WIDTHS[@]}"; do
    (( t > w )) && continue # never upscale
    sips -s format avif -s formatOptions "$QUALITY" --resampleWidth "$t" "$f" --out "$OUT/$base-$t.avif" >/dev/null
    made+=("$t")
  done
  # Always offer the original width too if it sits between the steps (e.g. 1400px)
  if (( w < 1920 )) && [[ ! " ${made[*]} " == *" $w "* ]] && (( w > 640 )); then
    sips -s format avif -s formatOptions "$QUALITY" "$f" --out "$OUT/$base-$w.avif" >/dev/null
    made+=("$w")
  fi
  echo "  '/images/$name': [$(IFS=,; echo "${made[*]}" | sed 's/,/, /g')]," >> "$MANIFEST"
  echo "✓ $name (${w}px) → ${made[*]}"
done

echo "};" >> "$MANIFEST"
echo "Manifest written to $MANIFEST"
